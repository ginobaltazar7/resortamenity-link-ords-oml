CREATE TABLE amenity_transactions (
 ingest_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 transaction_id VARCHAR2(100) NOT NULL,
 opera_guest_id VARCHAR2(100) NOT NULL,
 amenity_type VARCHAR2(30) NOT NULL,
 booking_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
 amount_spent_jpy NUMBER(12,0) NOT NULL,
 raw_payload BLOB,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT check_amenity_type CHECK (amenity_type IN ('SPA_TREATMENT', 'SKI_RENTAL', 'LIFT_TICKET', 'PRIVATE_GUIDE')),
 CONSTRAINT check_positive_spend CHECK (amount_spent_jpy >= 0),
 CONSTRAINT ensure_valid_json_payload CHECK (raw_payload IS JSON)
);

CREATE UNIQUE INDEX idx_unique_vendor_tx ON amenity_transactions(transaction_id);
CREATE INDEX idx_guest_amenity_search ON amenity_transactions(opera_guest_id, amenity_type);

CREATE TABLE amenity_analytics_cache (
 opera_guest_id VARCHAR2(100) PRIMARY KEY,
 total_spa_spend_jpy NUMBER(12,0) DEFAULT 0,
 total_ski_spend_jpy NUMBER(12,0) DEFAULT 0,
 total_lift_spend_jpy NUMBER(12,0) DEFAULT 0,
 total_guide_spend_jpy NUMBER(12,0) DEFAULT 0,
 amenity_visit_count NUMBER(6,0) DEFAULT 0,
 last_updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE VIEW v_amenity_deep_analytics AS
SELECT
 t.ingest_id, t.transaction_id, t.opera_guest_id, t.amenity_type, t.booking_timestamp, t.amount_spent_jpy,
 CASE WHEN JSON_EXISTS(t.raw_payload, '$.service_details.item_name')
      THEN t.raw_payload.service_details.item_name ELSE NULL END AS specific_service_name,
 CASE WHEN JSON_EXISTS(t.raw_payload, '$.service_details.duration_minutes')
      THEN t.raw_payload.service_details.duration_minutes ELSE NULL END AS service_duration
FROM amenity_transactions t;
